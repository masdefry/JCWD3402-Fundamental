// > BASIC OPERATOR
// +, -, /, *, %
var firstNumber = 100;
var secondNumber = 5;

console.log(firstNumber + secondNumber);
console.log(firstNumber - secondNumber);
console.log(firstNumber / secondNumber);
console.log(firstNumber * secondNumber);



// Modulus (Sisa Bagi)
console.log(10 % 3); // 9 -> 10-9=1
console.log(6 % 4); // 4 -> 6-4=2
console.log(8 % 4); // 8 -> 8-8=0



